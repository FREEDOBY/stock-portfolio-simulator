"""사이클 판정기 백테스트.

이미 결과를 아는 과거 구간(앵커)과 판정기 출력을 비교한다.
앵커는 이 단지의 실측 데이터(고점·저점 사이클 카드)와 공지의 시장 사실로 정의:
  2021-09 전후 고점 확정, 2022년 급락, 2022말~2023 저점 후 회복, 2024~2025 상승.
"""

import cycle

# 앵커는 이 단지의 실측 피벗(고점·저점 사이클 카드)에 맞춰 정의한다.
# 2016~2021 대세상승 중에도 8·2 대책(2017)·9·13 대책(2018) 후 실측 -13~-22%
# 조정이 있었으므로 해당 구간은 상승 앵커에서 제외하거나 하락으로 라벨링.
ANCHORS = [
    ("200810", "200903", "하락"),   # 금융위기 급락 (실측 -35~-41%)
    ("201006", "201212", "하락"),   # 장기 침체 (실측 고점→저점 -29~-35%)
    ("201302", "201312", "저점"),   # 바닥 다지기 (실측 저점 2013.04)
    ("201601", "201809", "상승"),   # 대세 상승 1파 (실측 고점 2018.10)
    ("201811", "201904", "하락"),   # 9·13 후 실측 조정 (14.1억→10.9억, -22%)
    ("201908", "202106", "상승"),   # 대세 상승 2파
    ("202110", "202202", "고점"),   # 실측 고점 2021.09 직후
    ("202204", "202211", "하락"),   # 금리 급등기 급락 (실측 -28~-34%)
    ("202301", "202309", "저점"),   # 실측 저점 2022.12/2023.01 후 횡보
    ("202405", "202506", "상승"),   # 재상승 (전고점 회복)
]


def main():
    rows = {r["ym"]: r for r in cycle.compute_phases()}
    total_hit = total_n = 0
    print(f"{'구간':22} {'정답':6} {'적중률':8} 판정 분포")
    for a, b, want in ANCHORS:
        got = [rows[ym]["phase"] for ym in rows if a <= ym <= b]
        hit = sum(1 for g in got if g == want)
        dist = {}
        for g in got:
            dist[g] = dist.get(g, 0) + 1
        total_hit += hit
        total_n += len(got)
        print(f"{a}~{b:8} {want:6} {hit:>3}/{len(got):<4} {dist}")
    print(f"\n전체 적중률: {total_hit}/{total_n} = {total_hit/total_n*100:.0f}%")
    last = rows[max(rows)]
    print(f"\n현재({last['ym']}) 판정: {last['phase']}  "
          f"(dd={last['dd']}%, mom3={last['mom3']}%, mom12={last['mom12']}%, "
          f"금리인상={last['hiking']}, 거래수준={last['vol_ratio']})")


if __name__ == "__main__":
    main()
